create or replace function public.has_portfolio_access(target_portfolio_id uuid)
returns boolean
language sql
stable
as $$
  select exists (
    select 1 from public.portfolios p
    where p.id = target_portfolio_id and p.owner_id = (select auth.uid())
  ) or exists (
    select 1 from public.portfolio_members pm
    where pm.portfolio_id = target_portfolio_id and pm.user_id = (select auth.uid())
  );
$$;

create or replace view public.project_execution_summary
with (security_invoker = true)
as
select
  p.portfolio_id,
  p.id as project_id,
  p.project_code,
  p.project_name,
  coalesce(b.budgeted_amount, 0)::numeric as budgeted_amount,
  coalesce(a.actual_amount, 0)::numeric as actual_amount,
  (coalesce(b.budgeted_amount, 0) - coalesce(a.actual_amount, 0))::numeric as variance,
  case when coalesce(b.budgeted_amount, 0) = 0 then 0
       else round((coalesce(a.actual_amount, 0) / b.budgeted_amount * 100)::numeric, 2)
  end as execution_percent
from public.projects p
left join (
  select bl.project_id, sum(bl.amount) as budgeted_amount
  from public.budget_lines bl
  join public.imports i on i.id = bl.import_id and i.is_active = true and i.source_type = 'budget'
  group by bl.project_id
) b on b.project_id = p.id
left join (
  select al.project_id, sum(al.amount) as actual_amount
  from public.actual_lines al
  join public.imports i on i.id = al.import_id and i.is_active = true and i.source_type = 'actual'
  group by al.project_id
) a on a.project_id = p.id;

