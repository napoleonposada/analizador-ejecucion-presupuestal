create extension if not exists pgcrypto;

create table if not exists public.portfolios (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 1 and 160),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.portfolio_members (
  portfolio_id uuid not null references public.portfolios(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('owner', 'editor', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (portfolio_id, user_id)
);

create table if not exists public.imports (
  id uuid primary key default gen_random_uuid(),
  portfolio_id uuid not null references public.portfolios(id) on delete cascade,
  uploaded_by uuid not null references auth.users(id) on delete restrict,
  source_type text not null check (source_type in ('budget', 'actual')),
  original_filename text not null,
  storage_path text,
  row_count integer not null default 0 check (row_count >= 0),
  status text not null default 'pending' check (status in ('pending', 'processing', 'completed', 'failed')),
  error_message text,
  is_active boolean not null default false,
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

create unique index if not exists imports_one_active_type_idx on public.imports (portfolio_id, source_type) where is_active;

create table if not exists public.projects (
  id uuid primary key default gen_random_uuid(),
  portfolio_id uuid not null references public.portfolios(id) on delete cascade,
  project_code text not null,
  project_name text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (portfolio_id, project_code)
);

